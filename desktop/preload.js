const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("flacApi", {
  getInitialState: () => ipcRenderer.invoke("get-initial-state"),
  pickAndScanFolder: () => ipcRenderer.invoke("pick-and-scan-folder"),
  rescanFolders: () => ipcRenderer.invoke("rescan-folders"),
  removeFolder: (folder) => ipcRenderer.invoke("remove-folder", folder),
  loadLyrics: (payload) => ipcRenderer.invoke("load-lyrics", payload),
  fetchOnlineCover: (payload) => ipcRenderer.invoke("fetch-online-cover", payload),
  getCoverDataUrl: (coverPath) => ipcRenderer.invoke("get-cover-data-url", coverPath),
  pickLrcFile: () => ipcRenderer.invoke("pick-lrc-file"),
  pickBackgroundFile: () => ipcRenderer.invoke("pick-background-file"),
  recordTrackPlayed: (trackId) => ipcRenderer.invoke("record-track-played", trackId),
  clearRecentlyPlayed: () => ipcRenderer.invoke("clear-recently-played"),
  saveLyricOffset: (trackId, offsetMs) =>
    ipcRenderer.invoke("save-lyric-offset", { trackId, offsetMs }),
  toggleFavorite: (trackId) => ipcRenderer.invoke("toggle-favorite", trackId),
  createPlaylist: (name) => ipcRenderer.invoke("create-playlist", name),
  deletePlaylist: (playlistId) => ipcRenderer.invoke("delete-playlist", playlistId),
  addTrackToPlaylist: (playlistId, trackId) =>
    ipcRenderer.invoke("add-track-to-playlist", { playlistId, trackId }),
  removeTrackFromPlaylist: (playlistId, trackId) =>
    ipcRenderer.invoke("remove-track-from-playlist", { playlistId, trackId }),
  saveEqConfig: (eqConfig) => ipcRenderer.invoke("save-eq-config", eqConfig),
  saveSettings: (settings) => ipcRenderer.invoke("save-settings", settings),
  exportTheme: (themeName) => ipcRenderer.invoke("export-theme", themeName),
  importTheme: (filePath) => ipcRenderer.invoke("import-theme", filePath),
  onMediaAction: (cb) => {
    ipcRenderer.on("media-action", (_, action) => cb(action));
  },
  nativeIsAvailable: () => ipcRenderer.invoke("native-is-available"),
  nativeGetDevices: () => ipcRenderer.invoke("native-get-devices"),
  nativeSetDevice: (deviceId) => ipcRenderer.invoke("native-set-device", deviceId),
  nativeSetExclusive: (enabled) => ipcRenderer.invoke("native-set-exclusive", enabled),
  nativeLoadFile: (filePath) => ipcRenderer.invoke("native-load-file", filePath),
  nativePreloadNext: (filePath) => ipcRenderer.invoke("native-preload-next", filePath),
  nativeStart: () => ipcRenderer.invoke("native-start"),
  nativePause: () => ipcRenderer.invoke("native-pause"),
  nativeStop: () => ipcRenderer.invoke("native-stop"),
  nativeSeekSeconds: (seconds) => ipcRenderer.invoke("native-seek-seconds", seconds),
  nativeSetVolume: (vol) => ipcRenderer.invoke("native-set-volume", vol),
  nativeBeginPauseFade: (ms) => ipcRenderer.invoke("native-begin-pause-fade", ms),
  nativeCancelPauseFade: () => ipcRenderer.invoke("native-cancel-pause-fade"),
  nativeStartCrossfade: (ms) => ipcRenderer.invoke("native-start-crossfade", ms),
  nativeCancelCrossfade: () => ipcRenderer.invoke("native-cancel-crossfade"),
  nativePromotePreloaded: () => ipcRenderer.invoke("native-promote-preloaded"),
  nativeSetReplayGain: (enabled) => ipcRenderer.invoke("native-set-replay-gain", enabled),
  nativeSetGapless: (enabled) => ipcRenderer.invoke("native-set-gapless", enabled),
  nativeUpdateEq: (eqConfig) => ipcRenderer.invoke("native-update-eq", eqConfig),
  nativeGetStatus: () => ipcRenderer.invoke("native-get-status"),
  savePlaybackState: (payload) => ipcRenderer.send("save-playback-state", payload),
  savePlaybackStateNow: (payload) => ipcRenderer.sendSync("save-playback-state-now", payload),
  mprisUpdate: (payload) => ipcRenderer.send("mpris-update", payload),
});
